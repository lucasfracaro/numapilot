//! Opções que só valem a partir do boot, aplicadas de um jeito que sobrevive às atualizações do
//! kernel: opções de módulo em /etc/modprobe.d (não dependem do bootloader nem da versão do kernel)
//! e a imagem de boot (initramfs) refeita com a ferramenta da distro.

use std::path::PathBuf;

/// Arquivo gerenciado pelo numapilot.
pub fn conf_path() -> PathBuf {
    std::env::var_os("NUMAPILOT_MODPROBE_CONF")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("/etc/modprobe.d/numapilot.conf"))
}

/// Bit do OverDrive (PP_OVERDRIVE_MASK) no amdgpu.ppfeaturemask.
pub const OVERDRIVE_BIT: u64 = 0x4000;

fn parse_hex(s: &str) -> Option<u64> {
    let s = s.trim();
    match s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
        Some(h) => u64::from_str_radix(h, 16).ok(),
        None => s.parse().ok(),
    }
}

/// Valor em uso agora pelo driver (None = amdgpu não carregado).
pub fn current_mask() -> Option<u64> {
    let p = crate::util::sys("module/amdgpu/parameters/ppfeaturemask");
    crate::util::read_trim(p).and_then(|s| parse_hex(&s))
}

/// Valor definido na linha do kernel (amdgpu.ppfeaturemask=...), que tem prioridade.
pub fn cmdline_mask() -> Option<u64> {
    let c = std::fs::read_to_string("/proc/cmdline").ok()?;
    c.split_whitespace()
        .find_map(|w| w.strip_prefix("amdgpu.ppfeaturemask="))
        .and_then(parse_hex)
}

/// Valor salvo no nosso arquivo.
pub fn saved_mask() -> Option<u64> {
    let s = std::fs::read_to_string(conf_path()).ok()?;
    s.lines()
        .filter(|l| !l.trim_start().starts_with('#'))
        .flat_map(|l| l.split_whitespace())
        .find_map(|w| w.strip_prefix("ppfeaturemask="))
        .and_then(parse_hex)
}

#[derive(Debug, Clone, PartialEq)]
pub struct OverdriveState {
    /// Ativo agora (o driver carregou com o bit).
    pub active: bool,
    /// Vai estar ativo depois de reiniciar.
    pub on_next_boot: bool,
    /// A linha do kernel define o valor (nosso arquivo é ignorado).
    pub from_cmdline: bool,
}

/// ppfeaturemask definido em qualquer arquivo do modprobe.d (o nosso ou outro).
pub fn any_modprobe_mask() -> Option<u64> {
    if let Some(m) = saved_mask() {
        return Some(m);
    }
    for dir in ["/etc/modprobe.d", "/usr/lib/modprobe.d", "/run/modprobe.d"] {
        let Ok(rd) = std::fs::read_dir(dir) else {
            continue;
        };
        let mut files: Vec<_> = rd.flatten().map(|e| e.path()).collect();
        files.sort();
        for f in files {
            let s = std::fs::read_to_string(&f).unwrap_or_default();
            if let Some(m) = s
                .lines()
                .filter(|l| !l.trim_start().starts_with('#') && l.contains("amdgpu"))
                .flat_map(|l| l.split_whitespace())
                .find_map(|w| w.strip_prefix("ppfeaturemask="))
                .and_then(parse_hex)
            {
                return Some(m);
            }
        }
    }
    None
}

pub fn overdrive_state() -> OverdriveState {
    let active = current_mask().is_some_and(|m| m & OVERDRIVE_BIT != 0);
    let cmd = cmdline_mask();
    let on_next_boot = match (cmd, any_modprobe_mask()) {
        (Some(m), _) | (None, Some(m)) => m & OVERDRIVE_BIT != 0,
        // ninguém define: é o padrão do kernel (o do CachyOS já vem com o OverDrive)
        (None, None) => active,
    };
    OverdriveState {
        active,
        on_next_boot,
        from_cmdline: cmd.is_some(),
    }
}

/// Máscara a gravar: a atual com só o bit do OverDrive ligado (não mexe em mais nada).
pub fn overdrive_mask(base: u64) -> u64 {
    base | OVERDRIVE_BIT
}

fn render(mask: Option<u64>, ttm_pages: Option<u64>) -> String {
    let mut s = String::from(
        "# Generated by numapilot (Settings, boot section). Edit it from the interface or\n\
         # with `sudo numapilot boot ...`. Applies to any installed kernel.\n",
    );
    if let Some(m) = mask {
        s.push_str("# OverDrive das placas AMD (clock/voltagem: undervolt e overclock)\n");
        s.push_str(&format!("options amdgpu ppfeaturemask=0x{m:x}\n"));
    }
    if let Some(p) = ttm_pages {
        s.push_str(&format!(
            "# Memory the integrated GPU/APU may use ({:.1} GiB; 4 KiB pages)\n",
            p as f64 * 4096.0 / 1073741824.0
        ));
        s.push_str(&format!("options ttm pages_limit={p} page_pool_size={p}\n"));
    }
    s
}

/// Limite de memória da GPU (páginas de 4 KiB) salvo no nosso arquivo.
pub fn saved_ttm() -> Option<u64> {
    let s = std::fs::read_to_string(conf_path()).ok()?;
    s.lines()
        .filter(|l| !l.trim_start().starts_with('#'))
        .flat_map(|l| l.split_whitespace())
        .find_map(|w| w.strip_prefix("pages_limit="))
        .and_then(|v| v.parse().ok())
}

/// Limite em uso agora (páginas de 4 KiB).
pub fn ttm_now() -> Option<u64> {
    crate::util::read_u64(crate::util::sys("module/ttm/parameters/pages_limit"))
}

pub fn gib_to_pages(gib: f64) -> u64 {
    (gib * 1073741824.0 / 4096.0).round() as u64
}

/// Memória total do sistema (GiB).
pub fn mem_total_gib() -> f64 {
    std::fs::read_to_string("/proc/meminfo")
        .ok()
        .and_then(|s| {
            s.lines()
                .find_map(|l| l.strip_prefix("MemTotal:"))
                .and_then(|r| r.split_whitespace().next()?.parse::<f64>().ok())
        })
        .map(|kb| kb / 1048576.0)
        .unwrap_or(0.0)
}

fn write_conf(text: &str, empty: bool, log: &mut dyn FnMut(&str)) -> Result<bool, String> {
    let path = conf_path();
    let old = std::fs::read_to_string(&path).ok();
    if old.as_deref() == Some(text) {
        log(crate::i18n::tr("Nothing changed in the file."));
        return Ok(false);
    }
    if empty && old.is_none() {
        log(crate::i18n::tr("It was already off."));
        return Ok(false);
    }
    if let Some(o) = &old {
        let _ = std::fs::write(path.with_extension("conf.bak"), o);
    }
    if empty {
        std::fs::remove_file(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        log(&crate::tf!("Removed {}", "Removido {}", path.display()));
    } else {
        if let Some(d) = path.parent() {
            std::fs::create_dir_all(d).map_err(|e| e.to_string())?;
        }
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
        log(&crate::tf!("Wrote {}", "Gravado {}", path.display()));
    }
    Ok(true)
}

/// Memória que a GPU integrada (APU, BC-250) pode usar para IA/jogos: grava no boot e tenta
/// aplicar já. None = volta ao padrão do kernel (metade da RAM).
pub fn set_gpu_memory(gib: Option<f64>, log: &mut dyn FnMut(&str)) -> Result<(), String> {
    if !crate::util::is_root() {
        return Err(crate::i18n::tr(
            "needs root (use sudo, or the interface button asks for the password)",
        )
        .into());
    }
    let total = mem_total_gib();
    let pages = match gib {
        Some(g) if g < 1.0 || (total > 0.0 && g > total - 1.0) => {
            return Err(crate::tf!(
                "value out of range: 1 to {:.0} GiB (leave at least 1 GiB for the system)",
                "valor fora da faixa: 1 a {:.0} GiB (deixe ao menos 1 GiB para o sistema)",
                (total - 1.0).max(1.0)
            ));
        }
        Some(g) => Some(gib_to_pages(g)),
        None => None,
    };
    let mask = saved_mask();
    let text = render(mask, pages);
    let changed = write_conf(&text, mask.is_none() && pages.is_none(), log)?;
    if let Some(p) = pages {
        for f in ["pages_limit", "page_pool_size"] {
            match std::fs::write(
                crate::util::sys(&format!("module/ttm/parameters/{f}")),
                p.to_string(),
            ) {
                Ok(()) => log(&crate::tf!(
                    "ttm {f}={p} applied now (applies to the next programs)",
                    "ttm {f}={p} aplicado agora (vale para os próximos programas)"
                )),
                Err(e) => log(&crate::tf!(
                    "ttm {f}: could not apply now ({e}); applies after a reboot",
                    "ttm {f}: não deu para aplicar agora ({e}); vale depois de reiniciar"
                )),
            }
        }
    }
    if changed {
        regenerate(log)?;
    }
    log(crate::i18n::tr("Done. Kernel updates keep the option."));
    Ok(())
}

/// Ferramenta que refaz a imagem de boot, na ordem de preferência.
pub fn initramfs_tool() -> Option<Vec<&'static str>> {
    let has = |b: &str| crate::containers::which(b);
    if has("limine-mkinitcpio") {
        Some(vec!["limine-mkinitcpio"])
    } else if has("mkinitcpio") {
        Some(vec!["mkinitcpio", "-P"])
    } else if has("dracut") {
        Some(vec!["dracut", "--regenerate-all", "--force"])
    } else if has("update-initramfs") {
        Some(vec!["update-initramfs", "-u", "-k", "all"])
    } else {
        None
    }
}

pub fn regenerate(log: &mut dyn FnMut(&str)) -> Result<(), String> {
    let Some(cmd) = initramfs_tool() else {
        log(crate::i18n::tr(
            "No initramfs tool found; the file applies when the module loads from disk.",
        ));
        return Ok(());
    };
    log(&crate::tf!(
        "Rebuilding the boot image: {}",
        "Refazendo a imagem de boot: {}",
        cmd.join(" ")
    ));
    let st = std::process::Command::new(cmd[0])
        .args(&cmd[1..])
        .status()
        .map_err(|e| format!("{}: {e}", cmd[0]))?;
    if st.success() {
        Ok(())
    } else {
        Err(crate::tf!(
            "{} finished with an error ({st})",
            "{} terminou com erro ({st})",
            cmd[0]
        ))
    }
}

/// Liga/desliga o OverDrive no boot. Precisa de root.
pub fn set_overdrive(on: bool, log: &mut dyn FnMut(&str)) -> Result<(), String> {
    if !crate::util::is_root() {
        return Err(crate::i18n::tr(
            "needs root (use sudo, or the interface button asks for the password)",
        )
        .into());
    }
    if let Some(m) = cmdline_mask() {
        log(&crate::tf!(
            "Warning: the kernel command line already sets amdgpu.ppfeaturemask=0x{m:x}, and it takes priority over this file.",
            "Aviso: a linha do kernel já define amdgpu.ppfeaturemask=0x{m:x}, e ela tem prioridade sobre este arquivo."
        ));
    }
    let new = if on {
        // Parte do valor em uso (padrão do driver) para não mudar outros recursos.
        let base = saved_mask().or_else(current_mask).unwrap_or(0xfff7_bfff);
        Some(overdrive_mask(base))
    } else {
        None
    };
    let ttm = saved_ttm();
    let text = render(new, ttm);
    if !write_conf(&text, new.is_none() && ttm.is_none(), log)? && new.is_none() && ttm.is_none() {
        return Ok(());
    }
    if let Some(m) = new {
        log(&format!("ppfeaturemask=0x{m:x}"));
    }
    regenerate(log)?;
    log(crate::i18n::tr(
        "Done. Reboot the computer to apply. Kernel updates keep the option.",
    ));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn masks() {
        assert_eq!(parse_hex("0xfff7bfff"), Some(0xfff7bfff));
        assert_eq!(parse_hex("4294426623"), Some(0xfff7bfff));
        assert_eq!(overdrive_mask(0xfff7bfff), 0xfff7ffff);
        assert_eq!(overdrive_mask(0xfffd7fff), 0xfffd7fff);
        assert!(render(Some(0xfff7ffff), None).contains("options amdgpu ppfeaturemask=0xfff7ffff"));
        assert!(!render(None, None).contains("options"));
        let r = render(None, Some(gib_to_pages(16.0)));
        assert!(
            r.contains("options ttm pages_limit=4194304 page_pool_size=4194304"),
            "{r}"
        );
    }
}
